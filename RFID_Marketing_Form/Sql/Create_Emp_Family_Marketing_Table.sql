-- SPERS.EMP_FAMILY_MARKETING — employee dependent / family RFID cards
-- Links to primary employee in SPERS.RFID_CARD_ASSIGN_MARKETING via EMP_ID.
-- Card display ID format: {EMP_ID}-{DEPENDENT_ID}  e.g. 25130-2
-- Oracle 11g+. Run as SPERS or a user with CREATE TABLE / SEQUENCE privilege.

-- Optional: drop for clean re-run (comment out in production)
-- DROP TABLE SPERS.EMP_FAMILY_MARKETING CASCADE CONSTRAINTS;
-- DROP SEQUENCE SPERS.EMP_FAMILY_MARKETING_SEQ;

CREATE SEQUENCE SPERS.EMP_FAMILY_MARKETING_SEQ
  START WITH 1
  INCREMENT BY 1
  NOCACHE
  NOCYCLE;

CREATE TABLE SPERS.EMP_FAMILY_MARKETING (
  ID                 NUMBER          NOT NULL,
  EMP_ID             VARCHAR2(20)    NOT NULL,
  DEPENDENT_ID       NUMBER          NOT NULL,
  CARD_ID            VARCHAR2(30)    NOT NULL,
  CARD_NAME          VARCHAR2(100)   NOT NULL,
  RELATIONSHIP       VARCHAR2(50)    NOT NULL,
  CNIC               VARCHAR2(20),
  RFID_NUMBER        VARCHAR2(50),
  ISSUE_DATE         DATE,
  EXPIRY_DATE        DATE,
  ISSUED_BY          VARCHAR2(50),
  PRINT_DATE         DATE,
  CREATED_DATE       DATE            DEFAULT SYSDATE NOT NULL,
  STATUS             VARCHAR2(20)    DEFAULT 'Active' NOT NULL,
  STATUS_REMARKS     VARCHAR2(500),
  IS_APPROVED        VARCHAR2(1)     DEFAULT 'N' NOT NULL,
  APPROVED_DATE      DATE,
  APPROVE_ID         NUMBER,
  HOD_REMARKS        VARCHAR2(500),
  IS_FORWARD_HOD     VARCHAR2(1)     DEFAULT 'N' NOT NULL,
  FORWARD_HOD_BY     VARCHAR2(100),
  FORWARD_HOD_ON     DATE,
  REQUESTER_REMARKS  VARCHAR2(500),
  IMAGE_PATH         VARCHAR2(500),
  CONSTRAINT PK_EMP_FAMILY_MARKETING PRIMARY KEY (ID),
  CONSTRAINT UK_EMP_FAMILY_CARD_ID UNIQUE (CARD_ID),
  CONSTRAINT UK_EMP_FAMILY_EMP_DEP UNIQUE (EMP_ID, DEPENDENT_ID),
  CONSTRAINT CK_EMP_FAMILY_STATUS CHECK (STATUS IN ('Active', 'Inactive')),
  CONSTRAINT CK_EMP_FAMILY_APPROVED CHECK (IS_APPROVED IN ('Y', 'N')),
  CONSTRAINT CK_EMP_FAMILY_FWD CHECK (IS_FORWARD_HOD IN ('Y', 'N'))
);

CREATE INDEX SPERS.IX_EMP_FAMILY_EMP_ID ON SPERS.EMP_FAMILY_MARKETING (EMP_ID);
CREATE INDEX SPERS.IX_EMP_FAMILY_RFID ON SPERS.EMP_FAMILY_MARKETING (RFID_NUMBER);

COMMENT ON TABLE SPERS.EMP_FAMILY_MARKETING IS
  'RFID family / dependent cards for employees listed in RFID_CARD_ASSIGN_MARKETING.';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.EMP_ID IS
  'Primary employee ID (must exist on employee RFID assignment).';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.DEPENDENT_ID IS
  'Sequence per employee: 1, 2, 3… used in CARD_ID.';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.CARD_ID IS
  'Printed card ID, typically EMP_ID || ''-'' || DEPENDENT_ID.';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.CARD_NAME IS
  'Dependent name as printed on the family card.';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.RELATIONSHIP IS
  'Relationship to employee (e.g. MOTHER, SPOUSE, SON).';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.CNIC IS
  'Dependent CNIC as printed on the card.';
COMMENT ON COLUMN SPERS.EMP_FAMILY_MARKETING.IMAGE_PATH IS
  'Relative path to dependent photo under Photos folder.';

COMMIT;
