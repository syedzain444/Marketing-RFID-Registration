-- Marketing RFID app — users, roles, permissions (Oracle 11g+)
-- Run as SPERS (or schema owner). Adjust schema prefix if needed.

CREATE TABLE SPERS.APP_ROLES_MARKETING (
  ROLE_CODE     VARCHAR2(30 BYTE)  NOT NULL,
  ROLE_NAME     VARCHAR2(80 BYTE)  NOT NULL,
  DESCRIPTION   VARCHAR2(200 BYTE),
  SORT_ORDER    NUMBER(5)          DEFAULT 0 NOT NULL,
  IS_ACTIVE     CHAR(1 BYTE)       DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_APP_ROLES_MKT PRIMARY KEY (ROLE_CODE),
  CONSTRAINT CK_APP_ROLES_MKT_ACT CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE SPERS.APP_PERMISSIONS_MARKETING (
  PERMISSION_CODE VARCHAR2(60 BYTE) NOT NULL,
  PERMISSION_NAME VARCHAR2(120 BYTE) NOT NULL,
  CATEGORY        VARCHAR2(40 BYTE) NOT NULL,
  DESCRIPTION     VARCHAR2(200 BYTE),
  SORT_ORDER      NUMBER(5)         DEFAULT 0 NOT NULL,
  CONSTRAINT PK_APP_PERM_MKT PRIMARY KEY (PERMISSION_CODE)
);

CREATE TABLE SPERS.APP_ROLE_PERMISSIONS_MARKETING (
  ROLE_CODE       VARCHAR2(30 BYTE)  NOT NULL,
  PERMISSION_CODE VARCHAR2(60 BYTE)  NOT NULL,
  CONSTRAINT PK_APP_ROLE_PERM_MKT PRIMARY KEY (ROLE_CODE, PERMISSION_CODE),
  CONSTRAINT FK_APP_RP_MKT_ROLE FOREIGN KEY (ROLE_CODE)
    REFERENCES SPERS.APP_ROLES_MARKETING (ROLE_CODE),
  CONSTRAINT FK_APP_RP_MKT_PERM FOREIGN KEY (PERMISSION_CODE)
    REFERENCES SPERS.APP_PERMISSIONS_MARKETING (PERMISSION_CODE)
);

CREATE SEQUENCE SPERS.APP_USERS_MKT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SPERS.APP_USERS_MARKETING (
  ID              NUMBER           NOT NULL,
  EMP_ID          VARCHAR2(20 BYTE) NOT NULL,
  PASSWORD_HASH   VARCHAR2(250 BYTE) NOT NULL,
  ROLE_CODE       VARCHAR2(30 BYTE) NOT NULL,
  DISPLAY_NAME    VARCHAR2(100 BYTE),
  IS_ACTIVE       CHAR(1 BYTE)     DEFAULT 'Y' NOT NULL,
  CREATED_DATE    DATE             DEFAULT SYSDATE NOT NULL,
  LAST_LOGIN      DATE,
  CONSTRAINT PK_APP_USERS_MKT PRIMARY KEY (ID),
  CONSTRAINT UK_APP_USERS_MKT_EMP UNIQUE (EMP_ID),
  CONSTRAINT CK_APP_USERS_MKT_ACT CHECK (IS_ACTIVE IN ('Y','N')),
  CONSTRAINT FK_APP_USERS_MKT_ROLE FOREIGN KEY (ROLE_CODE)
    REFERENCES SPERS.APP_ROLES_MARKETING (ROLE_CODE)
);

CREATE OR REPLACE TRIGGER SPERS.TR_APP_USERS_MKT_BI
BEFORE INSERT ON SPERS.APP_USERS_MARKETING
FOR EACH ROW
WHEN (NEW.ID IS NULL)
BEGIN
  SELECT SPERS.APP_USERS_MKT_SEQ.NEXTVAL INTO :NEW.ID FROM DUAL;
END;
/

-- Roles
MERGE INTO SPERS.APP_ROLES_MARKETING t
USING (
  SELECT 'HR' AS ROLE_CODE, 'HR' AS ROLE_NAME, 'Human Resources' AS DESCRIPTION, 10 AS SORT_ORDER FROM DUAL UNION ALL
  SELECT 'MARKETING_HEAD', 'Marketing Head', 'Marketing department head', 20 FROM DUAL UNION ALL
  SELECT 'SECURITY', 'Security', 'Security desk', 30 FROM DUAL UNION ALL
  SELECT 'ADMIN', 'Admin', 'Full system administrator', 99 FROM DUAL
) s ON (t.ROLE_CODE = s.ROLE_CODE)
WHEN NOT MATCHED THEN
  INSERT (ROLE_CODE, ROLE_NAME, DESCRIPTION, SORT_ORDER, IS_ACTIVE)
  VALUES (s.ROLE_CODE, s.ROLE_NAME, s.DESCRIPTION, s.SORT_ORDER, 'Y');

-- Permissions (screens + actions)
MERGE INTO SPERS.APP_PERMISSIONS_MARKETING t
USING (
  SELECT 'screen.form' AS PERMISSION_CODE, 'RFID request form' AS PERMISSION_NAME, 'Screens' AS CATEGORY, 10 AS SORT_ORDER FROM DUAL UNION ALL
  SELECT 'screen.records', 'Records list', 'Screens', 20 FROM DUAL UNION ALL
  SELECT 'screen.admin', 'Administration', 'Screens', 90 FROM DUAL UNION ALL
  SELECT 'action.form.save', 'Save new RFID record', 'RFID form', 110 FROM DUAL UNION ALL
  SELECT 'action.form.clear', 'Clear RFID form', 'RFID form', 120 FROM DUAL UNION ALL
  SELECT 'action.records.list', 'Load records grid', 'Records', 210 FROM DUAL UNION ALL
  SELECT 'action.records.view', 'View record details', 'Records', 220 FROM DUAL UNION ALL
  SELECT 'action.records.edit', 'Edit employee profile', 'Records', 230 FROM DUAL UNION ALL
  SELECT 'action.records.print', 'Print ID card', 'Records', 240 FROM DUAL UNION ALL
  SELECT 'action.records.status', 'Toggle Active/Inactive', 'Records', 250 FROM DUAL UNION ALL
  SELECT 'action.records.photo', 'Upload employee photo', 'Records', 260 FROM DUAL UNION ALL
  SELECT 'admin.users', 'Manage application users', 'Admin', 310 FROM DUAL UNION ALL
  SELECT 'admin.roles', 'Manage role permissions', 'Admin', 320 FROM DUAL
) s ON (t.PERMISSION_CODE = s.PERMISSION_CODE)
WHEN NOT MATCHED THEN
  INSERT (PERMISSION_CODE, PERMISSION_NAME, CATEGORY, SORT_ORDER)
  VALUES (s.PERMISSION_CODE, s.PERMISSION_NAME, s.CATEGORY, s.SORT_ORDER);

-- Default grants (Admin = all; tune others in Admin UI)
INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'ADMIN', p.PERMISSION_CODE FROM SPERS.APP_PERMISSIONS_MARKETING p
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x
  WHERE x.ROLE_CODE = 'ADMIN' AND x.PERMISSION_CODE = p.PERMISSION_CODE
);

-- HR defaults
INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'HR', c FROM (
  SELECT 'screen.form' AS c FROM DUAL UNION ALL SELECT 'screen.records' FROM DUAL UNION ALL
  SELECT 'action.form.save' FROM DUAL UNION ALL SELECT 'action.form.clear' FROM DUAL UNION ALL
  SELECT 'action.records.list' FROM DUAL UNION ALL SELECT 'action.records.view' FROM DUAL UNION ALL
  SELECT 'action.records.edit' FROM DUAL UNION ALL SELECT 'action.records.print' FROM DUAL UNION ALL
  SELECT 'action.records.photo' FROM DUAL UNION ALL SELECT 'action.records.status' FROM DUAL
) d
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x WHERE x.ROLE_CODE = 'HR' AND x.PERMISSION_CODE = d.c
);

-- Marketing Head defaults (same as HR without status toggle)
INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'MARKETING_HEAD', c FROM (
  SELECT 'screen.form' AS c FROM DUAL UNION ALL SELECT 'screen.records' FROM DUAL UNION ALL
  SELECT 'action.form.save' FROM DUAL UNION ALL SELECT 'action.form.clear' FROM DUAL UNION ALL
  SELECT 'action.records.list' FROM DUAL UNION ALL SELECT 'action.records.view' FROM DUAL UNION ALL
  SELECT 'action.records.edit' FROM DUAL UNION ALL SELECT 'action.records.print' FROM DUAL UNION ALL
  SELECT 'action.records.photo' FROM DUAL
) d
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x WHERE x.ROLE_CODE = 'MARKETING_HEAD' AND x.PERMISSION_CODE = d.c
);

-- Security defaults (read + print)
INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'SECURITY', c FROM (
  SELECT 'screen.records' AS c FROM DUAL UNION ALL
  SELECT 'action.records.list' FROM DUAL UNION ALL SELECT 'action.records.view' FROM DUAL UNION ALL
  SELECT 'action.records.print' FROM DUAL
) d
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x WHERE x.ROLE_CODE = 'SECURITY' AND x.PERMISSION_CODE = d.c
);

