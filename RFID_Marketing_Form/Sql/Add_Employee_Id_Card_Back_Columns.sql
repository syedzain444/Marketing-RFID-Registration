-- SPERS.RFID_CARD_ASSIGN_MARKETING — ID card back fields
-- Joining Date, Blood Group, CNIC, Emergency #
-- Oracle 11g+. Run as SPERS or a user with ALTER privilege on this table.

ALTER TABLE SPERS.RFID_CARD_ASSIGN_MARKETING ADD (
  JOINING_DATE  DATE,
  BLOOD_GROUP   VARCHAR2(20 BYTE),
  CNIC          VARCHAR2(20 BYTE),
  EMERGENCY_NO  VARCHAR2(30 BYTE)
);

COMMENT ON COLUMN SPERS.RFID_CARD_ASSIGN_MARKETING.JOINING_DATE IS
  'Employee joining date (printed on ID card back).';
COMMENT ON COLUMN SPERS.RFID_CARD_ASSIGN_MARKETING.BLOOD_GROUP IS
  'Blood group (e.g. O-, B+).';
COMMENT ON COLUMN SPERS.RFID_CARD_ASSIGN_MARKETING.CNIC IS
  'National ID (CNIC).';
COMMENT ON COLUMN SPERS.RFID_CARD_ASSIGN_MARKETING.EMERGENCY_NO IS
  'Emergency contact number.';

COMMIT;
