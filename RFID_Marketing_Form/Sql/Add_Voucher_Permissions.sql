-- Payment voucher screen permissions (Oracle). Run as SPERS.

MERGE INTO SPERS.APP_PERMISSIONS_MARKETING t
USING (
  SELECT 'screen.vouchers' AS PERMISSION_CODE, 'Payment vouchers desk' AS PERMISSION_NAME, 'Screens' AS CATEGORY, 25 AS SORT_ORDER FROM DUAL UNION ALL
  SELECT 'action.vouchers.list', 'List payment vouchers', 'Vouchers', 270 FROM DUAL UNION ALL
  SELECT 'action.vouchers.manage', 'Mark vouchers paid or unpaid', 'Vouchers', 280 FROM DUAL
) s ON (t.PERMISSION_CODE = s.PERMISSION_CODE)
WHEN NOT MATCHED THEN
  INSERT (PERMISSION_CODE, PERMISSION_NAME, CATEGORY, SORT_ORDER)
  VALUES (s.PERMISSION_CODE, s.PERMISSION_NAME, s.CATEGORY, s.SORT_ORDER);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'ADMIN', p.PERMISSION_CODE FROM SPERS.APP_PERMISSIONS_MARKETING p
WHERE p.PERMISSION_CODE IN ('screen.vouchers', 'action.vouchers.list', 'action.vouchers.manage')
AND NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x
  WHERE x.ROLE_CODE = 'ADMIN' AND x.PERMISSION_CODE = p.PERMISSION_CODE
);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'MARKETING_HEAD', c FROM (
  SELECT 'screen.vouchers' AS c FROM DUAL UNION ALL
  SELECT 'action.vouchers.list' FROM DUAL UNION ALL
  SELECT 'action.vouchers.manage' FROM DUAL
) d
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x WHERE x.ROLE_CODE = 'MARKETING_HEAD' AND x.PERMISSION_CODE = d.c
);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'HR', c FROM (
  SELECT 'screen.vouchers' AS c FROM DUAL UNION ALL
  SELECT 'action.vouchers.list' FROM DUAL UNION ALL
  SELECT 'action.vouchers.manage' FROM DUAL
) d
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x WHERE x.ROLE_CODE = 'HR' AND x.PERMISSION_CODE = d.c
);

COMMIT;
