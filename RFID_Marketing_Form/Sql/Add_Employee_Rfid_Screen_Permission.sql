-- Employee RFID Management screen permission (Oracle). Run as SPERS.

MERGE INTO SPERS.APP_PERMISSIONS_MARKETING t
USING (
  SELECT 'screen.employee.rfid' AS PERMISSION_CODE,
         'Employee RFID Management' AS PERMISSION_NAME,
         'Screens' AS CATEGORY,
         18 AS SORT_ORDER
  FROM DUAL
) s ON (t.PERMISSION_CODE = s.PERMISSION_CODE)
WHEN NOT MATCHED THEN
  INSERT (PERMISSION_CODE, PERMISSION_NAME, CATEGORY, SORT_ORDER)
  VALUES (s.PERMISSION_CODE, s.PERMISSION_NAME, s.CATEGORY, s.SORT_ORDER);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'ADMIN', 'screen.employee.rfid' FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x
  WHERE x.ROLE_CODE = 'ADMIN' AND x.PERMISSION_CODE = 'screen.employee.rfid'
);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'HR', 'screen.employee.rfid' FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x
  WHERE x.ROLE_CODE = 'HR' AND x.PERMISSION_CODE = 'screen.employee.rfid'
);

INSERT INTO SPERS.APP_ROLE_PERMISSIONS_MARKETING (ROLE_CODE, PERMISSION_CODE)
SELECT 'MARKETING_HEAD', 'screen.employee.rfid' FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM SPERS.APP_ROLE_PERMISSIONS_MARKETING x
  WHERE x.ROLE_CODE = 'MARKETING_HEAD' AND x.PERMISSION_CODE = 'screen.employee.rfid'
);

COMMIT;
