-- Payment vouchers for RFID Marketing records (Oracle 11g+)
-- Run as SPERS (or adjust schema). Links to employee assignment or family card row.

SET SERVEROUTPUT ON SIZE UNLIMITED;

DECLARE
  v_owner VARCHAR2(128) := 'SPERS';
BEGIN
  BEGIN
    EXECUTE IMMEDIATE
      'CREATE SEQUENCE ' || v_owner || '.CARD_VOUCHERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
    DBMS_OUTPUT.PUT_LINE('Created CARD_VOUCHERS_SEQ');
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE = -955 THEN
        DBMS_OUTPUT.PUT_LINE('CARD_VOUCHERS_SEQ already exists');
      ELSE
        RAISE;
      END IF;
  END;

  BEGIN
    EXECUTE IMMEDIATE '
      CREATE TABLE ' || v_owner || '.CARD_VOUCHERS (
        VOUCHER_ID      NUMBER           NOT NULL,
        ASSIGNMENT_ID   NUMBER           NOT NULL,
        RECORD_SCOPE    VARCHAR2(10 BYTE) DEFAULT ''EMPLOYEE'' NOT NULL,
        VOUCHER_NO      VARCHAR2(40 BYTE) NOT NULL,
        VOUCHER_TYPE    VARCHAR2(20 BYTE) DEFAULT ''INDIVIDUAL'' NOT NULL,
        REF_NO          VARCHAR2(50 BYTE),
        EMPLOYEE_NAME   VARCHAR2(120 BYTE),
        CNIC            VARCHAR2(30 BYTE),
        CATEGORY_NAME   VARCHAR2(80 BYTE),
        AMOUNT          NUMBER(12,2)     NOT NULL,
        CARD_COUNT      NUMBER(3)        DEFAULT 1 NOT NULL,
        STATUS          VARCHAR2(20 BYTE) DEFAULT ''GENERATED'' NOT NULL,
        GENERATED_BY    VARCHAR2(50 BYTE),
        GENERATED_ON    DATE             DEFAULT SYSDATE NOT NULL,
        PAID_BY         VARCHAR2(50 BYTE),
        PAID_ON         DATE,
        UPDATED_BY      VARCHAR2(50 BYTE),
        UPDATED_ON      DATE,
        REMARKS         VARCHAR2(500 BYTE),
        CONSTRAINT PK_CARD_VOUCHERS PRIMARY KEY (VOUCHER_ID),
        CONSTRAINT CK_CARD_VOUCHERS_SCOPE CHECK (RECORD_SCOPE IN (''EMPLOYEE'',''FAMILY'')),
        CONSTRAINT CK_CARD_VOUCHERS_STATUS CHECK (STATUS IN (''GENERATED'',''PAID'',''CANCELLED''))
      )';
    DBMS_OUTPUT.PUT_LINE('Created CARD_VOUCHERS');
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE = -955 THEN
        DBMS_OUTPUT.PUT_LINE('CARD_VOUCHERS already exists');
      ELSE
        RAISE;
      END IF;
  END;

  BEGIN
    EXECUTE IMMEDIATE
      'CREATE UNIQUE INDEX ' || v_owner || '.UK_CARD_VOUCHERS_ASSIGN ON ' || v_owner ||
      '.CARD_VOUCHERS (ASSIGNMENT_ID, RECORD_SCOPE, VOUCHER_TYPE)';
    DBMS_OUTPUT.PUT_LINE('Created UK_CARD_VOUCHERS_ASSIGN');
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE IN (-955, -1408) THEN
        DBMS_OUTPUT.PUT_LINE('Index UK_CARD_VOUCHERS_ASSIGN already exists');
      ELSE
        RAISE;
      END IF;
  END;

  BEGIN
    EXECUTE IMMEDIATE '
      CREATE OR REPLACE TRIGGER ' || v_owner || '.TR_CARD_VOUCHERS_BI
      BEFORE INSERT ON ' || v_owner || '.CARD_VOUCHERS
      FOR EACH ROW
      WHEN (NEW.VOUCHER_ID IS NULL)
      BEGIN
        SELECT ' || v_owner || '.CARD_VOUCHERS_SEQ.NEXTVAL INTO :NEW.VOUCHER_ID FROM DUAL;
      END;';
    DBMS_OUTPUT.PUT_LINE('Created trigger TR_CARD_VOUCHERS_BI');
  EXCEPTION
    WHEN OTHERS THEN
      DBMS_OUTPUT.PUT_LINE('Trigger note: ' || SQLERRM);
  END;
END;
/
